const gifts = document.getElementById('gifts');
const connection = document.getElementById('connection');
const alertBox = document.getElementById('alert');
const sourceRoute = location.pathname.replace(/\/+$/, '');
const sourceMode = sourceRoute.endsWith('/gifts') ? 'gifts' : sourceRoute.endsWith('/alerts') ? 'alerts' : sourceRoute.endsWith('/chaos') ? 'chaos' : 'vertical';
document.body.classList.add(`source-${sourceMode}`);
const alertQueue = [];
let alertBusy = false;
let alertSequence = 0;
let lastChaosLevel = 0;
const comboSuccesses = [];
let layout = { gameplayShare: 65, columns: 5, visibleCount: 20, compact: false, fontScale: 1, gap: 10, backgroundOpacity: 0.92, alertDurationMs: 4000, soundEnabled: true, iconScale: 1, cardBackground: '#272d22', cardBorder: '#5c694b' };
let audioContext;
let lastCatalog = [];
let lastEffects = [];
let pageIndex = 0;
let rotationTimer;
// OBS URLs generated by the dashboard include the per-install token. A missing
// token must fail authentication rather than silently using a predictable one.
const authToken = new URLSearchParams(location.search).get('token') || '';
let retryMs = 500;
let socket;
let disposed = false;
function connect() {
  if (disposed) return;
  socket = new WebSocket(`ws://${location.hostname}:39177`);
  socket.onopen = () => { retryMs = 500; socket.send(JSON.stringify({protocolVersion:1,type:'auth.hello',payload:{token:authToken,client:'overlay'}})); connection.textContent = 'ORCHESTRATOR CONNECTED'; };
  socket.onclose = () => { connection.textContent = 'ORCHESTRATOR OFFLINE'; if (!disposed) { setTimeout(connect, retryMs); retryMs = Math.min(10000, retryMs * 2); } };
  socket.onmessage = ({data}) => {
  try {
    const msg = JSON.parse(data);
    if (msg.type === 'catalog.snapshot') renderGifts(msg.payload);
    if (msg.type === 'effects.snapshot') { lastEffects = Array.isArray(msg.payload) ? msg.payload : []; renderGifts(lastCatalog); }
    if (msg.type === 'overlay.config') { layout = msg.payload; applyLayout(); renderGifts(lastCatalog); }
    if (msg.type === 'chaos.snapshot') { const level = Number(msg.payload.level); document.getElementById('chaos-level').textContent = String(level).padStart(2, '0'); document.querySelector('.bar i').style.width = `${msg.payload.points}%`; if (level > lastChaosLevel) showAlert(`CHAOS LEVEL ${level}`, undefined, 5 + level, 'chaos'); lastChaosLevel = level; }
    if (msg.type === 'result' && (msg.payload.status === 'succeeded' || msg.payload.status === 'failed')) { const result = msg.payload; const gift = lastCatalog.find((item) => item.name === result.giftName); const premium = gift?.costVerified === true && Number(gift.coinCost) >= 100; const failed = result.status === 'failed'; const priority = (premium ? 20 : 0) + (failed ? 10 : 0); const category = effectCategory(result.effectId); const prefix = premium ? 'PREMIUM · ' : ''; showAlert(`${prefix}${result.username || 'Viewer'} ${failed ? 'failed' : 'activated'} ${effectName(result.effectId) || result.error || 'unknown'} with ${result.giftName || 'gift'} × ${result.quantity || 1}`, result.imageUrl, priority, category, premium, failed); if (!failed) { const now = Date.now(); comboSuccesses.push(now); while (comboSuccesses.length && now - comboSuccesses[0] > 3000) comboSuccesses.shift(); if (comboSuccesses.length >= 3) showAlert(`COMBO ×${comboSuccesses.length}`, undefined, 12, 'combo'); } }
  } catch { /* OBS should keep rendering despite malformed local data */ }
  };
}
connect();
function renderGifts(items) {
  lastCatalog = Array.isArray(items) ? items : [];
  pageIndex = 0;
  if (rotationTimer) clearInterval(rotationTimer);
  renderGiftPage();
  // Keep the complete active catalog here. visibleCount is the page capacity;
  // truncating before calculating pages silently hid configured gifts.
  const activeCount = lastCatalog.filter((item) => item.active).length;
  const pageSize = Math.max(1, layout.visibleCount > 20 ? layout.columns * 2 : layout.visibleCount);
  if (Math.ceil(activeCount / pageSize) > 1) rotationTimer = setInterval(() => { pageIndex += 1; renderGiftPage(); }, 8000);
}
function renderGiftPage() {
  const active = lastCatalog.filter((item) => item.active);
  const pageSize = Math.max(1, layout.visibleCount > 20 ? layout.columns * 2 : layout.visibleCount);
  const pageCount = Math.max(1, Math.ceil(active.length / pageSize));
  pageIndex %= pageCount;
  const page = active.slice(pageIndex * pageSize, (pageIndex + 1) * pageSize);
  gifts.replaceChildren(...page.map((item) => {
    const card = document.createElement('div');
    card.className = 'gift';
    if (isSafeImageUrl(item.imageUrl)) {
      const image = document.createElement('img');
      image.src = item.imageUrl;
      image.alt = '';
      image.referrerPolicy = 'no-referrer';
      card.appendChild(image);
    } else {
      const fallback = document.createElement('span');
      fallback.className = 'gift-icon-fallback';
      fallback.textContent = 'NO ICON';
      fallback.setAttribute('aria-label', 'Gift icon unavailable');
      card.appendChild(fallback);
    }
    const name = document.createElement('strong');
    name.textContent = item.name;
    card.appendChild(name);
    const cost = document.createElement('small');
    cost.textContent = item.costVerified ? `${item.coinCost} COINS` : 'COST PENDING';
    card.appendChild(cost);
    if (Number(item.requiredQuantity) > 1) {
      const quantity = document.createElement('small');
      quantity.textContent = `REQUIRED ×${Math.floor(Number(item.requiredQuantity))}`;
      card.appendChild(quantity);
    }
    const effect = document.createElement('small');
    effect.textContent = item.effectIds?.map(effectName).filter(Boolean).join(' · ') || 'NO EFFECT ASSIGNED';
    card.appendChild(effect);
    return card;
  }));
}
function effectName(effectId) { return lastEffects.find((effect) => effect.id === effectId)?.name || effectId || ''; }
function effectCategory(effectId) { return (lastEffects.find((effect) => effect.id === effectId)?.category || 'GENERAL').toLowerCase().replace(/[^a-z0-9_-]/g, '-'); }
function applyLayout() {
  const gameplay = document.querySelector('.gameplay-space');
  const catalog = document.querySelector('.catalog');
  if (gameplay && sourceMode !== 'gifts') gameplay.style.height = `${1920 * layout.gameplayShare / 100}px`;
  if (catalog) catalog.style.height = sourceMode === 'gifts' ? '1920px' : `${1920 * (100 - layout.gameplayShare) / 100}px`;
  gifts.style.gridTemplateColumns = `repeat(${layout.columns}, 1fr)`;
  gifts.style.gap = `${layout.gap ?? 10}px`;
  gifts.style.setProperty('--gift-font-scale', String(layout.fontScale ?? 1));
  gifts.style.setProperty('--icon-scale', String(layout.iconScale ?? 1));
  gifts.style.setProperty('--catalog-opacity', String(layout.backgroundOpacity ?? 0.92));
  gifts.style.setProperty('--card-background', layout.cardBackground || '#272d22');
  gifts.style.setProperty('--card-border', layout.cardBorder || '#5c694b');
  gifts.classList.toggle('compact', layout.compact === true);
}
applyLayout();
function showAlert(text, imageUrl, priority = 0, category = 'general', premium = false, failed = false) { alertQueue.push({ text, imageUrl, priority, category, premium, failed, sequence: alertSequence++ }); alertQueue.sort((a, b) => b.priority - a.priority || a.sequence - b.sequence); if (!alertBusy) displayNextAlert(); }
function playAlertSound(category, premium, failed) { if (layout.soundEnabled !== true) return; try { const AudioContextCtor = window.AudioContext || window.webkitAudioContext; if (!AudioContextCtor) return; audioContext ||= new AudioContextCtor(); if (audioContext.state === 'suspended') audioContext.resume().catch(() => {}); const oscillator = audioContext.createOscillator(); const gain = audioContext.createGain(); const base = failed ? 160 : premium ? 880 : category === 'combo' ? 660 : category === 'chaos' ? 520 : 440; oscillator.type = premium ? 'triangle' : 'sine'; oscillator.frequency.value = base; gain.gain.setValueAtTime(0.0001, audioContext.currentTime); gain.gain.exponentialRampToValueAtTime(0.06, audioContext.currentTime + 0.01); gain.gain.exponentialRampToValueAtTime(0.0001, audioContext.currentTime + 0.18); oscillator.connect(gain).connect(audioContext.destination); oscillator.start(); oscillator.stop(audioContext.currentTime + 0.2); } catch { /* Browser autoplay/audio support is optional. */ } }
function displayNextAlert() { const alert = alertQueue.shift(); if (!alert) { alertBusy = false; return; } alertBusy = true; alertBox.replaceChildren(); if (isSafeImageUrl(alert.imageUrl)) { const image = document.createElement('img'); image.src = alert.imageUrl; image.alt = ''; image.referrerPolicy = 'no-referrer'; alertBox.appendChild(image); } else { const fallback = document.createElement('span'); fallback.className = 'gift-icon-fallback alert-icon-fallback'; fallback.textContent = 'NO ICON'; fallback.setAttribute('aria-label', 'Gift icon unavailable'); alertBox.appendChild(fallback); } const label = document.createElement('span'); label.textContent = alert.text; alertBox.appendChild(label); alertBox.className = `alert alert-${alert.category}${alert.premium ? ' alert-premium' : ''}${alert.failed ? ' alert-failed' : ''}`; alertBox.classList.remove('hidden'); playAlertSound(alert.category, alert.premium, alert.failed); setTimeout(() => { alertBox.classList.add('hidden'); alertBusy = false; displayNextAlert(); }, Math.max(1000, Math.min(10000, Number(layout.alertDurationMs) || 4000))); }
function isSafeImageUrl(value) { if (typeof value === 'string' && value.length <= 700000 && /^data:image\/(?:png|jpe?g|gif|webp);base64,[A-Za-z0-9+/=\s]+$/i.test(value)) return true; try { const url = new URL(String(value)); return url.protocol === 'https:' || url.protocol === 'http:'; } catch { return false; } }
